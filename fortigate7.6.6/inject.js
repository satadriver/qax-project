function ipToBinary(ipStr) {
    if (typeof ipStr !== 'string') {
        throw new Error('Invalid IPv4 address (not a string)');
    }

    // 1. 去除首尾空格
    const cleanIp = ipStr.trim();
    
    const parts = cleanIp.split('.').map(Number);
    
    // 2. 严格校验：必须是 4 段，且每段在 0-255 之间
    if (parts.length !== 4 || parts.some(p => p < 0 || p > 255 || isNaN(p))) {
        console.log(`[!] Failed to parse IP: "${cleanIp}"`);
        throw new Error('Invalid IPv4 address');
    }
    
    return Buffer.from(parts);
}

